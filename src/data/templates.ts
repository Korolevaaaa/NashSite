/* Ready-made templates for sale — detail pages at #/template/<slug>.
   Card-level data lives in storefront.ts (StoreItem.slug points here). */

export interface TemplateShot {
  src: string;
  label: string;
}

export interface TemplateProduct {
  slug: string; // latin, used in #/template/<slug>
  name: string; // short card name, e.g. «Доставка суши»
  title: string; // H1 on the detail page — SEO-strong
  seoTitle: string; // document.title
  seoDescription?: string; // meta description (~150 chars), иначе берётся description
  description: string; // lead paragraph under H1
  price: number; // RUB, shown as «от {price}»
  priceNote?: string;
  category: string; // matches StoreItem.cat
  animated?: boolean; // shows «анимированный макет» note + demo-request CTA
  hero: string; // big screenshot on top
  shots: TemplateShot[]; // labeled gallery
  features: { t: string; d: string }[]; // what the layout does
  includes: string[]; // what the buyer gets
  upsells: { t: string; d: string }[]; // optional add-ons, no prices
  fitFor: string[]; // target niches
  faq: { q: string; a: string }[];
}

